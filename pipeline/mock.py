def uniform_noise(shape: tuple[int, int], scale_cells: float, rng: np.random.Generator) -> np.ndarray:
    """Spatially smooth noise with uniform [0, 1] values: Gaussian-filtered white noise, rank-transformed.
    Thresholding it at f selects a fraction f of the area."""
    white = rng.standard_normal(shape)
    fy = np.fft.fftfreq(shape[0])[:, None]
    fx = np.fft.fftfreq(shape[1])[None, :]
    smooth = np.fft.ifft2(np.fft.fft2(white) * np.exp(-2 * (np.pi * scale_cells) ** 2 * (fx**2 + fy**2))).real
    ranks = np.empty(smooth.size)
    ranks[np.argsort(smooth, axis=None)] = np.arange(smooth.size)
    return (ranks / (smooth.size - 1)).reshape(shape)


def smoothstep(edge0: float, edge1: float, x: np.ndarray) -> np.ndarray:
    t = np.clip((x - edge0) / (edge1 - edge0), 0, 1)
    return t * t * (3 - 2 * t)


def voronoi_edge_distance(x: np.ndarray, y: np.ndarray, spacing: float, rng: np.random.Generator) -> np.ndarray:
    """Approximate distance (m) to the nearest edge of a jittered-grid Voronoi network, i.e. the boxwork
    polygon outlines. Worley noise (F2 - F1) / 2, one seed per spacing x spacing block."""
    blocks_x = int(x.max() // spacing) + 1
    blocks_y = int(y.max() // spacing) + 1
    jitter = rng.uniform(0.1, 0.9, size=(blocks_y + 2, blocks_x + 2, 2))  # +1 margin each side
    bx = np.floor(x / spacing).astype(int)
    by = np.floor(y / spacing).astype(int)
    d1 = np.full(x.shape, np.inf)
    d2 = np.full(x.shape, np.inf)
    for dy in (-1, 0, 1):
        for dx in (-1, 0, 1):
            i, j = bx + dx, by + dy
            sx = (i + jitter[j + 1, i + 1, 0]) * spacing
            sy = (j + jitter[j + 1, i + 1, 1]) * spacing
            d = np.hypot(x - sx, y - sy)
            d2 = np.minimum(d2, np.maximum(d1, d))
            d1 = np.minimum(d1, d)
    return (d2 - d1) / 2


def reachable_from(passable: np.ndarray, start: tuple[int, int]) -> np.ndarray:
    """Cells reachable from start over passable cells, 8-connected (vectorized breadth-first flood fill).
    Same moves as the app's route engine: a diagonal step may not squeeze between two blocked cells."""
    height, width = passable.shape
    flat = passable.ravel()
    reached = np.zeros(flat.size, bool)
    first = start[0] * width + start[1]
    reached[first] = True
    frontier = np.array([first])
    dr = np.array([-1, -1, -1, 0, 0, 1, 1, 1])
    dc = np.array([-1, 0, 1, -1, 1, -1, 0, 1])
    while frontier.size:
        r, c = np.divmod(frontier, width)
        r, c = np.repeat(r, 8), np.repeat(c, 8)
        nr, nc = r + np.tile(dr, frontier.size), c + np.tile(dc, frontier.size)
        ok = (nr >= 0) & (nr < height) & (nc >= 0) & (nc < width)
        r, c, nr, nc = r[ok], c[ok], nr[ok], nc[ok]
        diagonal = (nr != r) & (nc != c)
        ok = ~diagonal | (flat[nr * width + c] & flat[r * width + nc])
        n = nr[ok] * width + nc[ok]
        n = np.unique(n[flat[n] & ~reached[n]])
        reached[n] = True
        frontier = n
    return reached.reshape(height, width)


def block_mean(a: np.ndarray, block: int) -> np.ndarray:
    """Mean over block x block tiles, expanded back to a's shape: simulates a coarser instrument pixel."""
    rows, cols = np.arange(0, a.shape[0], block), np.arange(0, a.shape[1], block)
    sums = np.add.reduceat(np.add.reduceat(a, rows, axis=0), cols, axis=1)
    counts = np.add.reduceat(np.add.reduceat(np.ones(a.shape), rows, axis=0), cols, axis=1)
    return np.repeat(np.repeat(sums / counts, block, axis=0), block, axis=1)[: a.shape[0], : a.shape[1]]


def colormap(values: np.ndarray, stops: list[tuple[float, tuple[float, float, float]]]) -> np.ndarray:
    """Piecewise-linear colour ramp; values in [0, 1] -> uint8 RGB."""
    positions = [p for p, _ in stops]
    rgb = np.stack([np.interp(values, positions, [c[k] for _, c in stops]) for k in range(3)], axis=-1)
    return (rgb * 255).astype(np.uint8)


def generate_terrain(size_m: float, cell_size_m: float, seed: int) -> dict:
    """All mock rasters for a square site of side size_m. Returns arrays plus the masks used to place targets."""
    n = int(round(size_m / cell_size_m))
    shape = (n, n)
    rng = np.random.default_rng(seed)
    coords = (np.arange(n) + 0.5) * cell_size_m
    x = np.broadcast_to(coords[None, :], shape)  # east, m
    y = np.broadcast_to(coords[::-1, None], shape)  # north, m (row 0 = north edge)

    def cells(metres: float) -> float:
        return metres / cell_size_m

    # Regional rise toward Mount Sharp (south) plus gentle relief.
    elevation = C.MOCK_BASE_ELEVATION_M - C.MOCK_REGIONAL_GRADE * (y - size_m / 2)
    elevation = elevation + C.MOCK_UNDULATION_M * (2 * uniform_noise(shape, cells(C.MOCK_UNDULATION_SCALE_M), rng) - 1)

    # Habitat pad: no boxwork near the base.
    base_x, base_y = C.MOCK_BASE_XY_FRAC[0] * size_m, C.MOCK_BASE_XY_FRAC[1] * size_m
    clear_inner, clear_outer = (f * size_m for f in C.MOCK_BASE_CLEAR_FRAC)
    boxwork = smoothstep(clear_inner, clear_outer, np.hypot(x - base_x, y - base_y))

    # Boxwork ridges along polygon outlines, 1-2 m tall, broken into low saddles in places.
    edge = voronoi_edge_distance(x, y, C.MOCK_BOXWORK_SPACING_M, rng)
    top, flank = C.MOCK_RIDGE_TOP_HALF_WIDTH_M, C.MOCK_RIDGE_FLANK_WIDTH_M
    profile = 0.5 * (1 + np.cos(np.pi * np.clip((edge - top) / flank, 0, 1)))
    low, high = C.MOCK_RIDGE_HEIGHT_M
    ridge_height = low + (high - low) * uniform_noise(shape, cells(60), rng)
    f = C.MOCK_RIDGE_BREAK_FRACTION
    ridge_height = ridge_height * (0.1 + 0.9 * smoothstep(f - 0.04, f + 0.04, uniform_noise(shape, cells(40), rng)))
    ridge_height = ridge_height * boxwork
    elevation = elevation + ridge_height * profile

    # The steep wall: north-facing scarp, south side higher, tapering out to the east.
    amplitude = C.MOCK_WALL_AMPLITUDE_FRAC * size_m
    k = 2 * np.pi / (0.5 * size_m)
    wall_line = C.MOCK_WALL_Y_FRAC * size_m + amplitude * np.sin(k * x)
    north_of_wall = (y - wall_line) / np.sqrt(1 + (amplitude * k * np.cos(k * x)) ** 2)
    wall_taper = smoothstep(0, 1, (C.MOCK_WALL_END_X_FRAC * size_m - x) / C.MOCK_WALL_TAPER_M)
    wall_height = C.MOCK_WALL_HEIGHT_M * wall_taper
    elevation = elevation + wall_height / (1 + np.exp(np.clip(north_of_wall / C.MOCK_WALL_FACE_WIDTH_M, -50, 50)))
    wall_face = (np.abs(north_of_wall) < 3 * C.MOCK_WALL_FACE_WIDTH_M) & (wall_height > 2)

    # Boulder clusters (away from the habitat) and talus along the foot of the wall.
    patch = uniform_noise(shape, cells(6), rng)
    boulders = np.zeros(shape, bool)
    for _ in range(max(3, round(C.MOCK_BOULDER_CLUSTERS * (size_m / 2000) ** 2))):
        while True:
            cx, cy = rng.uniform(0, size_m, 2)
            if math.hypot(cx - base_x, cy - base_y) > clear_outer:
                break
        radius = rng.uniform(*C.MOCK_BOULDER_RADIUS_M)
        boulders |= (np.hypot(x - cx, y - cy) < radius) & (patch < 0.6)
    boulders |= (north_of_wall > 4) & (north_of_wall < 4 + 30 * wall_taper) & (wall_taper > 0.3) & (patch < 0.45)
    elevation = elevation + np.where(boulders & (rng.random(shape) < 0.2), rng.uniform(0.2, 0.8, shape), 0)

    # Loose sand on most hollow floors inside the boxwork; small patches on the habitat plain.
    hollow = edge > top + flank
    sand_noise = uniform_noise(shape, cells(15), rng)
    sand = np.where(boxwork > 0.5, hollow & (sand_noise < C.MOCK_SAND_FRACTION_IN_HOLLOWS), sand_noise < 0.15)

    terrain = np.full(shape, C.TERRAIN_BEDROCK, np.uint8)
    terrain[sand] = C.TERRAIN_SAND
    terrain[boulders] = C.TERRAIN_BOULDERS
    terrain[wall_face] = C.TERRAIN_NO_GO

    elevation = elevation.astype(np.float32)
    slope = slope_deg(elevation, cell_size_m)
    base_rc = (int((size_m - base_y) // cell_size_m), int(base_x // cell_size_m))
    passable = (slope < C.SLOPE_IMPASSABLE_DEG) & (terrain != C.TERRAIN_NO_GO)

    return {
        "sizeM": size_m,
        "cellSizeM": cell_size_m,
        "bounds": bounds_from_center(C.MOCK_CENTER_LAT, C.MOCK_CENTER_LON, size_m, size_m),
        "elevation": elevation,
        "slope": slope,
        "terrain": terrain,
        "x": x,
        "y": y,
        "profile": profile,
        "ridgeHeight": ridge_height,
        "boxwork": boxwork,
        "northOfWall": north_of_wall,
        "wallTaper": wall_taper,
        "baseRC": base_rc,
        "reachable": reachable_from(passable, base_rc),
        "rng": rng,
    }


def place_targets(t: dict) -> list[tuple[dict, tuple[int, int]]]:
    """For each TARGETS entry, the reachable cell meeting its criteria that is nearest its nominal position."""
    placed = []
    for spec in TARGETS:
        candidates = np.flatnonzero(spec["where"](t) & t["reachable"])
        if candidates.size == 0:
            raise RuntimeError(f"no reachable cell fits target {spec['id']}")
        px, py = spec["near"][0] * t["sizeM"], spec["near"][1] * t["sizeM"]
        d2 = (t["x"].ravel()[candidates] - px) ** 2 + (t["y"].ravel()[candidates] - py) ** 2
        rc = np.unravel_index(candidates[np.argmin(d2)], t["terrain"].shape)
        placed.append((spec, (int(rc[0]), int(rc[1]))))
    return placed


def surface_colors(t: dict) -> np.ndarray:
    """Mock surface colour (H, W, 3) in [0, 1], shaded by the terrain."""
    ridge_mix = np.clip(t["profile"] * t["boxwork"], 0, 1)[..., None]
    rgb = COLOR_BEDROCK * (1 - ridge_mix) + COLOR_RIDGE * ridge_mix
    rgb[t["terrain"] == C.TERRAIN_SAND] = COLOR_SAND
    rgb[t["terrain"] == C.TERRAIN_BOULDERS] = COLOR_BOULDERS
    shade = hillshade(t["elevation"], t["cellSizeM"])[..., None]
    rgb = rgb * (0.45 + 0.75 * shade) * (1 + 0.06 * t["rng"].standard_normal(t["terrain"].shape))[..., None]
    return np.clip(rgb, 0, 1)


def thermal_inertia(t: dict) -> np.ndarray:
    """Mock thermal inertia, degraded to the THEMIS pixel size."""
    ti = np.full(t["terrain"].shape, C.MOCK_TI["bedrock"])
    ti[t["profile"] * t["boxwork"] > 0.5] = C.MOCK_TI["ridge"]
    ti[t["terrain"] == C.TERRAIN_SAND] = C.MOCK_TI["sand"]
    ti[t["terrain"] == C.TERRAIN_BOULDERS] = C.MOCK_TI["boulders"]
    return block_mean(ti, max(1, round(C.MOCK_THEMIS_PIXEL_M / t["cellSizeM"])))


def mineralogy_rgb(t: dict) -> np.ndarray:
    """Mock 3-class mineral map at the CRISM pixel size: sulfate bedrock / vein-cemented ridges / basaltic sand."""
    block = max(1, round(C.MOCK_CRISM_PIXEL_M / t["cellSizeM"]))
    ridge_fraction = block_mean((t["profile"] * t["boxwork"] > 0.5).astype(float), block)
    sand_fraction = block_mean((t["terrain"] == C.TERRAIN_SAND).astype(float), block)
    rgb = np.empty(t["terrain"].shape + (3,), np.uint8)
    rgb[:] = (205, 180, 90)  # sulfate-bearing bedrock
    rgb[sand_fraction > 0.5] = (85, 90, 140)  # basaltic sand
    rgb[ridge_fraction > 0.25] = (110, 200, 210)  # vein-cemented ridges
    return rgb


def mock_conditions(lat_deg: float, start: datetime) -> list[dict]:
    """One sol of hourly conditions. Shapes loosely follow REMS diurnal cycles at Gale; values are MOCK.
    The sol is assumed to start at local midnight and the solar declination is taken as 0 (equinox)."""
    lat = math.radians(lat_deg)
    out = []
    for hour in range(25):
        hour_angle = math.radians(15 * (hour - 12))
        out.append(
            {
                # Millisecond precision: microseconds are not parsed by every browser's Date.
                "time": (start + timedelta(seconds=hour * C.MARS_SOL_S / 24)).isoformat(timespec="milliseconds").replace("+00:00", "Z"),
                "tempC": round(-40 - 35 * math.cos(2 * math.pi * (hour - 14) / 24), 1),
                "pressurePa": round(820 + 15 * math.cos(2 * math.pi * (hour - 8) / 24), 1),
                "dustTau": round(0.6 + 0.05 * math.sin(2 * math.pi * hour / 24), 3),
                "sunElevationDeg": round(math.degrees(math.asin(math.cos(lat) * math.cos(hour_angle))), 1),
                "radiationAlert": False,
                "source": "MOCK: synthetic diurnal cycle shaped like REMS at Gale; sun from declination 0",
                "status": "MOCK",
            }
        )
    return out


def _write_json(path: Path, data) -> None:
    path.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")


def build_mock(
    out_dir: Path,
    url_prefix: str = "processed/mock",
    size_m: float = C.MOCK_SIZE_M,
    cell_size_m: float = C.MOCK_CELL_SIZE_M,
    seed: int = C.MOCK_SEED,
    pov_width: int = C.POV_WIDTH_PX,
) -> dict:
    """Write the full mock dataset to out_dir. url_prefix is out_dir as seen from data/ (used in JSON paths)."""
    out_dir = Path(out_dir)
    (out_dir / "pov").mkdir(parents=True, exist_ok=True)
    t = generate_terrain(size_m, cell_size_m, seed)
    bounds, shape = t["bounds"], t["terrain"].shape

    write_costgrid(out_dir / "costgrid.json", t["elevation"], t["slope"], t["terrain"], cell_size_m, bounds, "MOCK", SOURCE)

    colors = surface_colors(t)
    write_png(out_dir / "optical.png", (colors @ np.array([0.299, 0.587, 0.114]) * 255).astype(np.uint8))
    write_png(out_dir / "hillshade.png", (hillshade(t["elevation"], cell_size_m) * 255).astype(np.uint8))
    ti_scaled = (np.log(thermal_inertia(t)) - math.log(150)) / (math.log(1200) - math.log(150))
    write_png(out_dir / "thermal_inertia.png", colormap(ti_scaled, [(0, (0.15, 0.1, 0.35)), (0.5, (0.8, 0.3, 0.25)), (1, (1, 0.9, 0.4))]))
    write_png(out_dir / "mineralogy.png", mineralogy_rgb(t))

    base_lat, base_lon = cell_center_latlon(bounds, shape, *t["baseRC"])
    rover_rc = (t["baseRC"][0], t["baseRC"][1] + round(30 / cell_size_m))
    rover_lat, rover_lon = cell_center_latlon(bounds, shape, *rover_rc)
    _write_json(
        out_dir / "waypoints.json",
        [
            {"id": "base", "lat": base_lat, "lon": base_lon, "kind": "base", "name": "Habitat"},
            {"id": "rover", "lat": rover_lat, "lon": rover_lon, "kind": "rover", "name": "Support rover (parked)"},
        ],
    )

    placed = place_targets(t)
    targets = []
    for spec, rc in placed:
        lat, lon = cell_center_latlon(bounds, shape, *rc)
        targets.append(
            {
                "id": spec["id"],
                "lat": lat,
                "lon": lon,
                "name": spec["name"],
                "why": spec["why"],
                "instrumentsNeeded": spec["instrumentsNeeded"],
                "source": "MOCK: placed on mock terrain by pipeline/mock.py",
                "status": "MOCK",
            }
        )
    _write_json(out_dir / "science_targets.json", targets)

    pov_height = pov_width // 4
    povs = []
    for pov_id, rc in [("base", t["baseRC"])] + [(spec["id"], rc) for spec, rc in placed]:
        image = render_panorama(
            t["elevation"], colors, cell_size_m, rc[0], rc[1],
            C.POV_EYE_HEIGHT_M, pov_width, pov_height, C.POV_VFOV_DEG, C.POV_MAX_DISTANCE_M,
        )  # fmt: skip
        write_png(out_dir / "pov" / f"{pov_id}.png", image)
        write_png(out_dir / "pov" / f"{pov_id}_thumb.png", image[::4, ::4])
        lat, lon = cell_center_latlon(bounds, shape, *rc)
        povs.append(
            {
                "lat": lat,
                "lon": lon,
                "url": f"{url_prefix}/pov/{pov_id}.png",
                "thumbnailUrl": f"{url_prefix}/pov/{pov_id}_thumb.png",
                "source": "MOCK: rendered from mock terrain by pipeline/panorama.py",
                "sol": 0,
                "camera": f"MOCK render, 360 deg, eye height {C.POV_EYE_HEIGHT_M} m",
                "isPanorama": True,
                "status": "MOCK",
            }
        )
    _write_json(out_dir / "pov_images.json", povs)

    _write_json(out_dir / "conditions.json", mock_conditions(base_lat, datetime(2026, 11, 15, tzinfo=timezone.utc)))

    total = t["terrain"].size
    return {
        "cells": f"{shape[1]} x {shape[0]} @ {cell_size_m} m",
        "bounds": bounds,
        "elevationRangeM": (round(float(t["elevation"].min()), 1), round(float(t["elevation"].max()), 1)),
        "fraction": {
            "sand": round(float((t["terrain"] == C.TERRAIN_SAND).sum() / total), 3),
            "boulders": round(float((t["terrain"] == C.TERRAIN_BOULDERS).sum() / total), 3),
            "noGo": round(float((t["terrain"] == C.TERRAIN_NO_GO).sum() / total), 3),
            "slopeImpassable": round(float((t["slope"] >= C.SLOPE_IMPASSABLE_DEG).sum() / total), 3),
            "reachableFromBase": round(float(t["reachable"].sum() / total), 3),
        },
    }
